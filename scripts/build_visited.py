def build():
    items = []
    for name, city, note in GD:
        items.append(mk(name, "广东", city, note))
    for prov, name, note in NONGD:
        items.append(mk(name, prov, "", note))
    for country, name, note in ABROAD:
        items.append(mk(name, country, "", note, scope="abroad"))
    return items


def mk(name, region, city, note, scope="cn"):
    d = {"name": name, "region": region, "city": city, "review": note, "scope": scope}
    if name in NOTWITH:
        d["notWith"] = NOTWITH[name]
    if name in REVISIT:
        d["policy"] = "revisit"
        d["revisit"] = REVISIT[name]
    elif name in BLOCK:
        d["policy"] = "block"
        d["blockReason"] = BLOCK[name]
    elif region in REGION_BLOCK:
        d["policy"] = "block"
        d["blockReason"] = REGION_BLOCK[region]
    else:
        d["policy"] = "exclude"
    return d


